-- Shared recipes (plan milestone 10): one row per recipe, hanging directly on
-- the household. Recipes sync like list items, through postgres_changes on
-- the household channel, so RLS stays the only security boundary.

create table recipes (
  id uuid primary key default gen_random_uuid(),
  household_id uuid not null references households (id) on delete cascade,
  title text not null,
  -- Free text like a shopping item's quantity ("4", "1 loaf"); nothing is
  -- calculated from it.
  servings text,
  -- [{ "id": uuid, "name": text, "quantity": text | null }, ...] in the order
  -- they were entered. One column rather than a table, so a recipe is one row
  -- to sync. The id is generated by the client and only identifies the
  -- ingredient within its recipe.
  ingredients jsonb not null default '[]',
  -- Plain text; the client keeps its line breaks.
  instructions text not null default '',
  created_by uuid not null references auth.users (id),
  created_at timestamptz not null default now(),
  -- No updated_at: no trigger would maintain it (see 0002).
  deleted_at timestamptz,
  -- The limits below exist because every recipe travels whole in a Realtime
  -- payload, and RLS can't limit the size of a row a member may insert.
  constraint recipes_title_shape check (
    title ~ '\S' and char_length(title) <= 200
  ),
  constraint recipes_servings_shape check (
    servings is null or (servings ~ '\S' and char_length(servings) <= 50)
  ),
  constraint recipes_instructions_length check (
    char_length(instructions) <= 20000
  ),
  constraint recipes_ingredients_shape check (
    case
      when jsonb_typeof(ingredients) = 'array' then
        jsonb_array_length(ingredients) <= 100
        -- Asked of the elements' types, not in the filter below: a filter
        -- unwraps an array before it looks at it, so an ingredient wrapped
        -- in a nested array would pass as the object inside.
        and not jsonb_path_exists(ingredients, '$[*].type() ? (@ != "object")')
        -- True for an ingredient that breaks a rule. A comparison with a
        -- missing key or a value of another type is "unknown", not true, so
        -- existence and type are tested before the text is.
        and not jsonb_path_exists(ingredients, '$[*] ? (
          !exists(@.id)
          || @.id.type() != "string"
          || !(@.id like_regex "^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")
          || !exists(@.name)
          || @.name.type() != "string"
          || !(@.name like_regex "\\S")
          || @.name like_regex "^.{201,}$" flag "s"
          || !exists(@.quantity)
          || (@.quantity.type() != "string" && @.quantity.type() != "null")
          || (@.quantity.type() == "string" && !(@.quantity like_regex "\\S"))
          || @.quantity like_regex "^.{51,}$" flag "s"
          || exists(@.keyvalue() ? (@.key != "id" && @.key != "name" && @.key != "quantity"))
        )')
      else false
    end
  )
);

-- For the cascade from households.
create index recipes_household_id_idx on recipes (household_id);
-- For loading a household's recipes: the live ones, paged by id. Partial,
-- because deleted recipes stay as rows (soft delete).
create index recipes_live_idx on recipes (household_id, id) where deleted_at is null;
create index recipes_created_by_idx on recipes (created_by);

alter table recipes enable row level security;

create policy "members rw recipes" on recipes
  for all to authenticated
  using (is_household_member(household_id)) with check (is_household_member(household_id));

-- Only what the app does: a recipe is written, edited or soft-deleted (an
-- UPDATE), never hard-deleted. A hard delete would also be invisible to the
-- other members, since Realtime is subscribed to INSERT and UPDATE only.
revoke all on recipes from public, anon, authenticated;
grant select, insert, update on recipes to authenticated;
grant select, insert, update, delete on recipes to service_role;

-- Without this the subscription succeeds but never receives an event (see 0011).
alter publication supabase_realtime add table public.recipes;

-- One to-do list and one shopping list per household, as for boards (0012):
-- two members opening a list for the first time at the same moment each
-- found none and created one, after which reading "the" list failed for that
-- household. Recipes add a second place that creates the shopping list on
-- first use. Drop the constraints when several lists are wanted.
alter table todo_lists
  add constraint todo_lists_household_id_key unique (household_id);
alter table shopping_lists
  add constraint shopping_lists_household_id_key unique (household_id);
